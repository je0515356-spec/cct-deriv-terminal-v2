export const getMarketBySymbol = (symbolOrFeed: string): MarketItem => {
  const found = POPULAR_MARKETS.find(
    (m) => m.symbol === symbolOrFeed || m.feedSymbol === symbolOrFeed
  );
  if (found) return found;

  // Fallback for custom active symbols returned from Deriv
  return {
    symbol: symbolOrFeed,
    feedSymbol: symbolOrFeed,
    displayName: symbolOrFeed,
    market: symbolOrFeed.startsWith('frxXAU') || symbolOrFeed.startsWith('frxXAG')
      ? 'metals'
      : symbolOrFeed.startsWith('frx')
      ? 'forex'
      : 'deriv',
    category: 'Market Symbol',
    decimals: 4,
    pipSize: 0.0001,
    sourceName: 'Deriv Public Datafeed',
    description: 'Real-time market feed provided by Deriv API.',
  };
};
